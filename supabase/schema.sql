alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.cart_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.newsletter_subscribers enable row level security;

-- Políticas para profiles
drop policy if exists "Profiles visible to authenticated users" on public.profiles;
create policy "Profiles visible to authenticated users"
  on public.profiles for select
  using (true);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles for update
  using (auth.uid() = id);

-- Políticas para products
-- La línea básica (alpaca) es pública; la premium exige sesión iniciada.
-- Así el bloqueo no depende solo del frontend: Supabase tampoco la entrega
-- a visitantes anónimas.
drop policy if exists "Products are viewable by everyone" on public.products;
drop policy if exists "Basic products are public" on public.products;
create policy "Basic products are public"
  on public.products for select
  using (is_active = true and tier = 'basico');

drop policy if exists "Premium products for authenticated" on public.products;
create policy "Premium products for authenticated"
  on public.products for select
  to authenticated
  using (is_active = true and tier = 'premium');

-- Políticas para cart_items (Solo el dueño puede ver y modificar su carrito)
drop policy if exists "Users can manage their own cart" on public.cart_items;
create policy "Users can manage their own cart"
  on public.cart_items for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- Políticas para orders (Los usuarios ven sus propios pedidos)
drop policy if exists "Users can view their own orders" on public.orders;
create policy "Users can view their own orders"
  on public.orders for select
  using (auth.uid() = user_id);

drop policy if exists "Users can insert their own orders" on public.orders;
create policy "Users can insert their own orders"
  on public.orders for insert
  with check (auth.uid() = user_id or auth.uid() is null);

-- Políticas para order_items
drop policy if exists "Users can view order items" on public.order_items;
create policy "Users can view order items"
  on public.order_items for select
  using (
    exists (
      select 1 from public.orders
      where orders.id = order_items.order_id
      and (orders.user_id = auth.uid() or auth.uid() is null)
    )
  );

drop policy if exists "Users can insert order items" on public.order_items;
create policy "Users can insert order items"
  on public.order_items for insert
  with check (true);

-- Políticas para newsletter
drop policy if exists "Anyone can subscribe to newsletter" on public.newsletter_subscribers;
create policy "Anyone can subscribe to newsletter"
  on public.newsletter_subscribers for insert
  with check (true);

