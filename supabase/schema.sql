create extension if not exists "uuid-ossp";

-- =============================================================================
-- TABLA: PERFILES DE USUARIO (public.profiles)
-- Se vincula automáticamente con auth.users de Supabase
-- =============================================================================
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  avatar_url text,
  phone text,
  address text,
  role text default 'customer' check (role in ('customer', 'admin')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Trigger para crear perfil automáticamente cuando un usuario se registra
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1))
  );
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- =============================================================================
-- TABLA: PRODUCTOS (public.products)
-- =============================================================================
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique,
  category text not null check (category in ('encaje', 'invisibles', 'seda', 'sets')),
  price numeric(10, 2) not null,
  tag text,
  description text not null,
  colors jsonb not null default '[]'::jsonb,
  is_active boolean default true,
  stock integer default 100,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- =============================================================================
-- TABLA: ITEMS DEL CARRITO (public.cart_items)
-- =============================================================================
create table if not exists public.cart_items (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  color_name text not null,
  color_hex text not null,
  size text not null default 'M',
  quantity integer not null default 1 check (quantity > 0),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique (user_id, product_id, color_name, size)
);

-- =============================================================================
-- TABLA: PEDIDOS / ÓRDENES (public.orders)
-- =============================================================================
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  customer_email text not null,
  customer_name text not null,
  status text not null default 'pending' check (status in ('pending', 'paid', 'shipped', 'delivered', 'cancelled')),
  subtotal numeric(10, 2) not null,
  shipping_cost numeric(10, 2) not null default 0.00,
  total numeric(10, 2) not null,
  shipping_address jsonb,
  notes text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- =============================================================================
-- TABLA: ITEMS DE PEDIDOS (public.order_items)
-- =============================================================================
create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  price numeric(10, 2) not null,
  quantity integer not null check (quantity > 0),
  color_name text,
  color_hex text,
  size text
);

-- =============================================================================
-- TABLA: SUSCRIPTORES AL NEWSLETTER (public.newsletter_subscribers)
-- =============================================================================
create table if not exists public.newsletter_subscribers (
  id uuid primary key default gen_random_uuid(),
  email text unique not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- =============================================================================
-- SEGURIDAD: ROW LEVEL SECURITY (RLS)
-- =============================================================================
alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.cart_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.newsletter_subscribers enable row level security;

-- Políticas para profiles
drop policy if exists "Profiles visible to authenticated users" on public.profiles;
create policy "Profiles visible to authenticated users"
  on public.profiles for select
  using (true);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles for update
  using (auth.uid() = id);

-- Políticas para products (Cualquiera puede ver productos)
drop policy if exists "Products are viewable by everyone" on public.products;
create policy "Products are viewable by everyone"
  on public.products for select
  using (is_active = true);

-- Políticas para cart_items (Solo el dueño puede ver y modificar su carrito)
drop policy if exists "Users can manage their own cart" on public.cart_items;
create policy "Users can manage their own cart"
  on public.cart_items for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- Políticas para orders (Los usuarios ven sus propios pedidos)
drop policy if exists "Users can view their own orders" on public.orders;
create policy "Users can view their own orders"
  on public.orders for select
  using (auth.uid() = user_id);

drop policy if exists "Users can insert their own orders" on public.orders;
create policy "Users can insert their own orders"
  on public.orders for insert
  with check (auth.uid() = user_id or auth.uid() is null);

-- Políticas para order_items
drop policy if exists "Users can view order items" on public.order_items;
create policy "Users can view order items"
  on public.order_items for select
  using (
    exists (
      select 1 from public.orders
      where orders.id = order_items.order_id
      and (orders.user_id = auth.uid() or auth.uid() is null)
    )
  );

drop policy if exists "Users can insert order items" on public.order_items;
create policy "Users can insert order items"
  on public.order_items for insert
  with check (true);

-- Políticas para newsletter
drop policy if exists "Anyone can subscribe to newsletter" on public.newsletter_subscribers;
create policy "Anyone can subscribe to newsletter"
  on public.newsletter_subscribers for insert
  with check (true);

