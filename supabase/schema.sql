create extension if not exists "uuid-ossp";

-- =============================================================================
-- TABLA: PERFILES DE USUARIO (public.profiles)
-- Se vincula automáticamente con auth.users de Supabase
-- =============================================================================
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  avatar_url text,
  phone text,
  address text,
  role text default 'customer' check (role in ('customer', 'admin')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Trigger para crear perfil automáticamente cuando un usuario se registra
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1))
  );
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- =============================================================================
-- TABLA: PRODUCTOS (public.products)
-- =============================================================================
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique,
  category text not null check (category in ('alpaca', 'premium')),
  -- 'basico' = visible sin sesión | 'premium' = solo con sesión iniciada
  tier text not null default 'basico' check (tier in ('basico', 'premium')),
  price numeric(10, 2) not null,
  tag text,
  description text not null,
  -- Ruta pública de la foto, ej: 'products/alpaca-verde-oscuro.jpg'
  image text not null default '',
  colors jsonb not null default '[]'::jsonb,
  is_active boolean default true,
  stock integer default 100,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Migración segura si ya tenías la tabla del catálogo anterior
alter table public.products add column if not exists tier text not null default 'basico';
alter table public.products add column if not exists image text not null default '';
alter table public.products drop constraint if exists products_category_check;
alter table public.products add constraint products_category_check check (category in ('alpaca', 'premium'));

-- =============================================================================
-- TABLA: ITEMS DEL CARRITO (public.cart_items)
-- =============================================================================
create table if not exists public.cart_items (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  color_name text not null,
  color_hex text not null,
  size text not null default 'M',
  quantity integer not null default 1 check (quantity > 0),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique (user_id, product_id, color_name, size)
);

-- =============================================================================
-- TABLA: PEDIDOS / ÓRDENES (public.orders)
-- =============================================================================
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  customer_email text not null,
  customer_name text not null,
  status text not null default 'pending' check (status in ('pending', 'paid', 'shipped', 'delivered', 'cancelled')),
  subtotal numeric(10, 2) not null,
  shipping_cost numeric(10, 2) not null default 0.00,
  total numeric(10, 2) not null,
  shipping_address jsonb,
  notes text,
  -- PayPal (ver supabase/migrations/20261112_paypal.sql)
  payment_provider text,
  payment_reference text,
  paypal_order_id text,
  paid_at timestamp with time zone,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Compatibilidad con bases de datos creadas antes de la integración de PayPal.
alter table public.orders
  add column if not exists payment_provider text,
  add column if not exists payment_reference text,
  add column if not exists paypal_order_id text,
  add column if not exists paid_at timestamp with time zone;

create unique index if not exists orders_paypal_order_id_key
  on public.orders (paypal_order_id)
  where paypal_order_id is not null;

-- =============================================================================
-- TABLA: ITEMS DE PEDIDOS (public.order_items)
-- =============================================================================
create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  price numeric(10, 2) not null,
  quantity integer not null check (quantity > 0),
  color_name text,
  color_hex text,
  size text
);

-- =============================================================================
-- TABLA: SUSCRIPTORES AL NEWSLETTER (public.newsletter_subscribers)
-- =============================================================================
create table if not exists public.newsletter_subscribers (
  id uuid primary key default gen_random_uuid(),
  email text unique not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

